std::string dSeriesToneLabel(int tone) {
    std::string label;
    if (tone >= 192) {
        const int number = tone - 192 + 1;
        label = std::string("r") + char('0' + number / 10) + char('0' + number % 10);
    } else {
        label = std::string(1, "abi"[tone / 64]) + char('1' + tone % 64 / 8) + char('1' + tone % 8);
    }
    return label + " " + kDSeriesToneNames[tone & 255];
}
