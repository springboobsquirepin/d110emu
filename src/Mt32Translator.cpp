void Mt32Translator::reset() {
    const uint8_t tuneAndReverb[4] = {0x4A, 0, 5, 3};  // Master tune (A = 442 Hz), reverb Room, time 6, level 3
    std::memcpy(system_.data(), tuneAndReverb, sizeof(tuneAndReverb));
    std::memcpy(&system_[kSystemReserves], kPowerOnReserves, sizeof(kPowerOnReserves));
    for (uint32_t part = 0; part < 9; part++) system_[kSystemChannels + part] = uint8_t(part + 1);  // MIDI channels 2-10
    system_[kSystemMasterVolume] = 100;
    for (int patch = 0; patch < 128; patch++) {
        patchMemory_[size_t(patch)] = {uint8_t(patch / 64), uint8_t(patch % 64), 24, 50, 12, 0, 1, 0};
    }
    for (int part = 0; part < 9; part++) {
        std::array<uint8_t, 16>& temp = patchTemp_[size_t(part)];
        temp.fill(0);
        if (part < 8) std::memcpy(temp.data(), patchMemory_[kPowerOnPrograms[part]].data(), 8);
        temp[2] = 24;
        temp[3] = 50;
        temp[4] = 12;
        temp[kReverbSwitch] = 1;
        temp[8] = 80;  // Output level
        temp[kPanpot] = mt32Pan(part < 8 ? kPowerOnPans[part] : 0);
        temp[kKeyRangeUpper] = 127;
    }
    for (std::array<uint8_t, 4>& key : rhythmSetup_) key = {127, 0, 7, 0};  // Unassigned
    for (const RhythmKey& entry : kPowerOnRhythm) {
        rhythmSetup_[size_t(entry.key - 24)] = {uint8_t(64 + entry.timbre), 100, mt32Pan(entry.pan), 1};
    }
    for (Tone& tone : toneTemp_) tone.written.reset();
    for (Tone& tone : toneMemory_) tone.written.reset();
    toneSent_.fill(true);
    toneToSend_.fill(false);
    volume_.fill(127);
    // The cache keeps what the unit's slots hold; nothing plays from them any more.
    partSlot_.fill(-1);
    slotFill_.fill(false);
    rhythmSlot_.fill(-1);
}

void Mt32Translator::powerOn(uint8_t deviceId, std::vector<uint8_t>& out, std::vector<uint32_t>& shortAfter) {
    reset();
    // Memories first, then the system area, then the parts, whose timbre selection loads their tones.
    std::vector<uint8_t> patches(128 * 8);
    for (size_t patch = 0; patch < 128; patch++) std::memcpy(&patches[patch * 8], patchMemory_[patch].data(), 8);
    for (uint32_t offset = 0; offset < patches.size(); offset += 256) {
        translateWrite(kPatchMemory + offset, &patches[offset], 256, deviceId, out, shortAfter);
    }
    std::vector<uint8_t> rhythm(85 * 4);
    for (size_t key = 0; key < 85; key++) std::memcpy(&rhythm[key * 4], rhythmSetup_[key].data(), 4);
    translateWrite(kRhythmSetup, rhythm.data(), 256, deviceId, out, shortAfter);
    translateWrite(kRhythmSetup + 256, rhythm.data() + 256, rhythm.size() - 256, deviceId, out, shortAfter);
    const std::array<uint8_t, kSystemSize> system = system_;
    translateWrite(kSystem, system.data(), system.size(), deviceId, out, shortAfter);
    uint8_t temps[9 * 16];
    for (size_t part = 0; part < 9; part++) std::memcpy(&temps[part * 16], patchTemp_[part].data(), 16);
    translateWrite(kPatchTemp, temps, sizeof(temps), deviceId, out, shortAfter);
    // The patch temp writes above already select the patches; program changes also number them, as the panel shows
    // (only where the unit holds the patch memory).
    std::vector<uint8_t> units;
    for (size_t part = 0; part < 8 && memoryInUnit_; part++) {
        unitChannelsFor(system_[kSystemChannels + part], units);
        for (uint8_t unit : units) shortAfter.push_back(uint32_t(0xC0 | unit) | (uint32_t(kPowerOnPrograms[part]) << 8));
    }
    if (masterVolumeAsVolume_) appendVolumes(shortAfter);
}

void Mt32Translator::translateShort(uint32_t message, uint8_t deviceId, std::vector<uint32_t>& shortOut, std::vector<uint8_t>& sysexAfter) {
    const uint8_t status = uint8_t(message & 0xFF);
    if (status < 0x80) return;
    if (status >= 0xF0) {
        shortOut.push_back(message);
        return;
    }
    const uint8_t channel = status & 0x0F;
    const uint8_t data1 = uint8_t((message >> 8) & 0x7F);
    uint8_t data2 = uint8_t((message >> 16) & 0x7F);
    bool restoreVolume = false;
    switch (status & 0xF0) {
    case 0xB0:
        if (data1 == 10) {
            data2 = uint8_t(127 - data2);  // Pan
        } else if (data1 == 7) {
            volume_[channel] = data2;
            data2 = scaledVolume(channel);
        } else if (data1 == 121) {
            restoreVolume = masterVolumeAsVolume_;  // The MT-32 keeps its volume; D-series units go to full
        }
        break;
    case 0xC0:
        programChange(channel, data1, deviceId, sysexAfter);
        if (!memoryInUnit_) return;  // The unit's own timbre memory is not the MT-32's: the SysEx above is the change
        break;
    default:
        break;
    }
    std::vector<uint8_t> units;
    unitChannelsFor(channel, units);
    for (uint8_t unit : units) {
        shortOut.push_back(uint32_t(status & 0xF0) | unit | (uint32_t(data1) << 8) | (uint32_t(data2) << 16));
        if (restoreVolume) shortOut.push_back(uint32_t(0xB0 | unit) | (7u << 8) | (uint32_t(scaledVolume(channel)) << 16));
    }
}

void Mt32Translator::setPartChannels(const uint8_t* channels) {
    for (size_t part = 0; part < 9; part++) system_[kSystemChannels + part] = std::min<uint8_t>(channels[part], 16);
}

bool Mt32Translator::isDSeriesData(const uint8_t* data, size_t length) {
    for (size_t i = 0; i < length;) {
        if (data[i] != 0xF0) {
            i++;
            continue;
        }
        size_t end = i + 1;
        while (end < length && data[end] != 0xF7) end++;
        if (end >= length) break;
        const size_t size = end + 1 - i;
        const uint8_t* message = data + i;
        i = end + 1;
        if (size < 10 || message[1] != 0x41 || message[3] != 0x16 || (message[4] != 0x12 && message[4] != 0x42)) continue;
        if (message[2] < 0x10) continue;  // Addressed by MIDI channel: MT-32 style
        const uint32_t address = pack(message[5], message[6], message[7]);
        const uint32_t last = address + uint32_t(size - 10) - (size > 10 ? 1 : 0);
        if (!inMt32Area(address) || !inMt32Area(last)) return true;
    }
    return false;
}

void Mt32Translator::translateSysex(const uint8_t* data, size_t length, uint8_t deviceId, std::vector<uint8_t>& out,
                                    std::vector<uint32_t>& shortAfter) {
    const bool rolandWrite = length >= 10 && data[0] == 0xF0 && data[1] == 0x41 && data[3] == 0x16 &&
                             (data[4] == 0x12 || data[4] == 0x42) && data[length - 1] == 0xF7;
    if (!rolandWrite || data[2] > 0x10) {
        // Not an MT-32 write (other models, other unit numbers, data requests): only readdress MT-32 requests.
        const size_t start = out.size();
        out.insert(out.end(), data, data + length);
        if (length >= 5 && data[0] == 0xF0 && data[1] == 0x41 && data[2] == 0x10 && data[3] == 0x16) out[start + 2] = deviceId;
        return;
    }
    if (data[5] == 0x7F) {
        powerOn(deviceId, out, shortAfter);  // Reset, taken before the checksum as mt32emu does
        return;
    }
    if (checksum(data + 5, length - 7) != data[length - 2]) return;  // Damaged: the synth would ignore it too
    uint32_t address = pack(data[5], data[6], data[7]);
    const uint8_t* bytes = data + 8;
    const size_t count = length - 10;
    const uint8_t device = data[2];
    if (device < 0x10) {
        // Addressed by MIDI channel: 00 00 xx is the patch temp area of the part(s) on the channel, 01 xx xx the
        // rhythm setup, 02 xx xx the part's tone. Parts are found as mt32emu does (the rhythm part like part 1).
        if (address >= pack(0x01, 0x00, 0x00) && address < pack(0x02, 0x00, 0x00)) {
            translateWrite(kRhythmSetup + (address - pack(0x01, 0x00, 0x00)), bytes, count, deviceId, out, shortAfter);
            return;
        }
        const bool patch = address < pack(0x01, 0x00, 0x00);
        const bool tone = address >= pack(0x02, 0x00, 0x00) && address < pack(0x03, 0x00, 0x00);
        if (!patch && !tone) return;
        const uint32_t offset = address - (patch ? 0 : pack(0x02, 0x00, 0x00));
        bool found = false;
        for (uint32_t part = 0; part < 9; part++) {
            if (system_[kSystemChannels + part] != device) continue;
            found = true;
            const uint32_t index = part == 8 ? 0 : part;
            translateWrite((patch ? kPatchTemp + index * 16 : kToneTemp + index * kToneSize) + offset, bytes, count, deviceId, out,
                           shortAfter);
        }
        if (!found) translateWrite((patch ? kPatchTemp : kToneTemp) + offset, bytes, count, deviceId, out, shortAfter);
        return;
    }
    translateWrite(address, bytes, count, deviceId, out, shortAfter);
}

// Translates one write of the MT-32 side and appends the unit's messages.
void Mt32Translator::translateWrite(uint32_t address, const uint8_t* data, size_t count, uint8_t deviceId, std::vector<uint8_t>& out,
                                    std::vector<uint32_t>& shortAfter) {
    if (count == 0) return;
    if (address >= kReset) {
        powerOn(deviceId, out, shortAfter);  // The D-series has no reset; set up what the MT-32 resets to
        return;
    }
    if (address >= kDisplay && address < kDisplay + 0x4000) {
        if (address == kDisplay && count <= 32) {
            // The MT-32 shows 20 characters; clear the rest of the D-series' 32.
            uint8_t text[32];
            std::memset(text, ' ', sizeof(text));
            std::memcpy(text, data, count);
            appendDataSet(out, deviceId, kDisplay, text, sizeof(text));
        } else {
            appendDataSet(out, deviceId, address, data, count);
        }
        return;
    }

    // Pass 1: the MT-32 side's memory, so that bytes depending on each other see the whole write.
    std::array<bool, 8> tempWasKnown{};
    std::array<bool, 64> memoryWasKnown{};
    for (size_t i = 0; i < 8; i++) tempWasKnown[i] = toneTemp_[i].known();
    for (size_t i = 0; i < 64; i++) memoryWasKnown[i] = toneMemory_[i].known();
    bool selects[8] = {};
    bool toneEdited[8] = {};
    std::array<bool, 85> rhythmKeys{};
    std::array<bool, 64> memoryChanged{};
    bool masterVolume = false;
    for (size_t i = 0; i < count; i++) {
        const uint32_t a = address + uint32_t(i);
        const uint8_t value = data[i] & 0x7F;
        if (a >= kPatchTemp && a < kRhythmSetup) {
            const uint32_t part = (a - kPatchTemp) / 16, offset = (a - kPatchTemp) % 16;
            patchTemp_[part][offset] = value;
            if (part < 8 && offset <= kNumber) selects[part] = true;
        } else if (a >= kRhythmSetup && a < kRhythmSetupEnd) {
            rhythmSetup_[(a - kRhythmSetup) / 4][(a - kRhythmSetup) % 4] = value;
            if ((a - kRhythmSetup) % 4 == 0) rhythmKeys[(a - kRhythmSetup) / 4] = true;
        } else if (a >= kToneTemp && a < kToneTempEnd) {
            const uint32_t part = (a - kToneTemp) / kToneSize;
            Tone& tone = toneTemp_[part];
            tone.data[(a - kToneTemp) % kToneSize] = value;
            tone.written.set((a - kToneTemp) % kToneSize);
            toneEdited[part] = true;
            partSlot_[part] = -1;  // The part no longer plays a slot's tone as it is
        } else if (a >= kPatchMemory && a < kPatchMemoryEnd) {
            patchMemory_[(a - kPatchMemory) / 8][(a - kPatchMemory) % 8] = value;
        } else if (a >= kToneMemory && a < kToneMemoryEnd && (a - kToneMemory) % 256 < kToneSize) {
            Tone& tone = toneMemory_[(a - kToneMemory) / 256];
            tone.data[(a - kToneMemory) % 256] = value;
            tone.written.set((a - kToneMemory) % 256);
            memoryChanged[(a - kToneMemory) / 256] = true;
        } else if (a >= kSystem && a < kSystem + kSystemSize) {
            system_[a - kSystem] = value;
            if (a - kSystem == kSystemMasterVolume) masterVolume = true;
        }
    }

    // A part whose timbre changed loads it into its tone, as on the MT-32; where it comes from on the unit (a cache
    // slot, or its tone temp) is decided before the unit's bytes, which point at the slot.
    for (int part = 0; part < 8; part++) {
        if (!selects[part]) continue;
        selectTimbre(part);
        resolveSlot(part);
    }
    // Rhythm keys that play memory timbres get them from the cache, also when the MT-32 side rewrote such a timbre.
    bool borrowed = false;
    if (cacheActive()) {
        for (int key = 0; key < 85; key++) {
            const uint8_t value = rhythmSetup_[size_t(key)][0];
            if (value < 64 && memoryChanged[value]) rhythmKeys[size_t(key)] = true;
            if (rhythmKeys[size_t(key)]) resolveRhythmKey(key, deviceId, out, borrowed);
        }
    }

    // Pass 2: the unit's bytes.
    Output output;
    for (size_t i = 0; i < count; i++) writeByte(address + uint32_t(i), data[i] & 0x7F, output);
    for (int key = 0; key < 85; key++) {
        if (rhythmKeys[size_t(key)]) writeByte(kRhythmSetup + uint32_t(key) * 4, rhythmSetup_[size_t(key)][0], output);
    }
    // A tone that is now complete is sent whole, with the pitch corrections its partials could not get so far; so is
    // an edited preset while the target plays a stand-in, which the edit would otherwise change instead.
    for (size_t i = 0; i < 8; i++) {
        if (toneEdited[i] && toneTemp_[i].known() && (!tempWasKnown[i] || !toneSent_[i])) {
            for (uint32_t offset = 0; offset < kToneSize; offset++) translateTone(toneTemp_[i], kToneTemp + uint32_t(i) * kToneSize, offset, output);
            toneSent_[i] = true;
        }
    }
    for (size_t i = 0; i < 64 && memoryInUnit_; i++) {
        if (!memoryWasKnown[i] && toneMemory_[i].known()) {
            for (uint32_t offset = 0; offset < kToneSize; offset++) translateTone(toneMemory_[i], kToneMemory + uint32_t(i) * 256, offset, output);
        }
    }
    emit(output, deviceId, out);
    sendTones(deviceId, out);
    if (borrowed) restorePart(7, deviceId, out);
    if (masterVolume && masterVolumeAsVolume_) appendVolumes(shortAfter);
}

void Mt32Translator::writeByte(uint32_t a, uint8_t value, Output& out) {
    if (a >= kPatchTemp && a < kRhythmSetup) {
        const uint32_t part = (a - kPatchTemp) / 16, offset = (a - kPatchTemp) % 16;
        const uint32_t base = kPatchTemp + part * 16;
        const std::array<uint8_t, 16>& temp = patchTemp_[part];
        if (offset <= kKeyShift && part < 8) {
            // Group and number select a tone (and decide the stand-in's key shift); a key shift alone must not, as
            // that would reload the tone on the unit.
            uint8_t patch[3];
            translatePatch(temp.data(), patch, int(part));
            for (uint32_t i = offset == kKeyShift ? kKeyShift : 0; i < 3; i++) out.set(base + i, patch[i]);
        } else if (offset == kReverbSwitch) {
            out.set(a, std::min<uint8_t>(value, 1));
        } else if (offset == kDummy) {
            out.set(a, 0);  // The MT-32's dummy is d110emu's card and extra-bank flag
        } else if (offset == kPanpot) {
            out.set(a, uint8_t(14 - std::min<uint8_t>(value, 14)));
        } else if (offset == kKeyRangeLower) {
            out.set(a, 0);
        } else if (offset == kKeyRangeUpper) {
            out.set(a, 127);
        } else {
            out.set(a, value);
        }
    } else if (a >= kRhythmSetup && a < kRhythmSetupEnd) {
        switch ((a - kRhythmSetup) % 4) {
        case 0:
            out.set(a, translateRhythmTimbre(value, int((a - kRhythmSetup) / 4)));
            break;
        case 2:
            out.set(a, uint8_t(14 - std::min<uint8_t>(value, 14)));
            break;
        case 3:
            out.set(a, std::min<uint8_t>(value, 1));  // Reverb switch -> output assign MIX (with or without reverb)
            break;
        default:
            out.set(a, value);
            break;
        }
    } else if (a >= kToneTemp && a < kToneTempEnd) {
        const uint32_t part = (a - kToneTemp) / kToneSize;
        translateTone(toneTemp_[part], kToneTemp + part * kToneSize, (a - kToneTemp) % kToneSize, out);
    } else if (a >= kPatchMemory && a < kPatchMemoryEnd) {
        if (!memoryInUnit_) return;  // Kept here: program changes send the parts' timbres
        const uint32_t patch = (a - kPatchMemory) / 8, offset = (a - kPatchMemory) % 8;
        if (offset <= kKeyShift) {
            uint8_t translated[3];
            translatePatch(patchMemory_[patch].data(), translated, -1);
            for (uint32_t i = offset == kKeyShift ? kKeyShift : 0; i < 3; i++) out.set(kPatchMemory + patch * 8 + i, translated[i]);
        } else {
            out.set(a, offset == kReverbSwitch ? std::min<uint8_t>(value, 1) : offset == kDummy ? 0 : value);
        }
    } else if (a >= kToneMemory && a < kToneMemoryEnd && (!memoryInUnit_ || (a - kToneMemory) % 256 < kToneSize)) {
        if (!memoryInUnit_) return;  // Kept here (with the slot's padding): timbre selections send the tone
        const uint32_t tone = (a - kToneMemory) / 256;
        translateTone(toneMemory_[tone], kToneMemory + tone * 256, (a - kToneMemory) % 256, out);
    } else if (a >= kSystem && a < kSystem + kSystemSize) {
        const uint32_t offset = a - kSystem;
        if (offset == kSystemReverbMode) {
            out.set(a, kReverbModes[std::min<uint8_t>(value, 3)]);
        } else if (offset >= kSystemReserves && offset < kSystemReserves + 9 && target_ == Target::D20) {
            // The D-20 takes partial reserves only as a package of all 9, at most 32 partials in total.
            unsigned total = 0;
            for (uint32_t part = 0; part < 9; part++) total += system_[kSystemReserves + part];
            for (uint32_t part = 0; part < 9; part++) {
                const unsigned reserve = system_[kSystemReserves + part];
                out.set(kSystem + kSystemReserves + part, uint8_t(total > 32 ? reserve * 32 / total : reserve));
            }
        } else if (offset >= kSystemChannels && offset < kSystemChannels + 9) {
            if (target_ != Target::D20) out.set(a, value);  // D-20: channels are set on the panel (a dummy here)
        } else if (offset == kSystemMasterVolume) {
            if (!masterVolumeAsVolume_ && target_ != Target::D20) out.set(a, value);  // Else CC 7 (see translateWrite)
        } else {
            out.set(a, value);
        }
    } else {
        out.set(a, value);  // Nothing to translate
    }
}

// Timbre group, number and key shift of a patch (temp or memory): M -> i, and presets A, B and R -> the D-110's a, b
// and r of the same number (preset banks), else the stand-ins; stand-ins with their key shift. A part whose tone the
// unit loads from a cache slot points at the slot.
void Mt32Translator::translatePatch(const uint8_t* patch, uint8_t* out, int part) const {
    const uint8_t group = patch[kGroup] & 3, number = patch[kNumber] & 63;
    int tone = group * 64 + number;
    int keyShift = patch[kKeyShift];
    if (part >= 0 && partSlot_[size_t(part)] >= 0 && cacheActive()) {
        tone = 128 + cacheFirst_ + partSlot_[size_t(part)];
    } else if (group < 2) {
        const PresetChoice& choice = presetChoices_[size_t(group * 64 + number)];
        if (!presetBanks()) tone = choice.tone;
        // An MT-32 timbre sent to the part (or held by the bank) replaces the stand-in, and needs no shift.
        if (!presetIsExact(group * 64 + number)) keyShift += choice.keyShift;
    } else if (group == 3) {
        const int standIn = rhythmStandIn(number);
        if (!presetBanks() || (!rhythmIsExact(number) && standIn == kRhythmOff)) tone = 192 + standIn;
    }
    out[0] = uint8_t(tone / 64);
    out[1] = uint8_t(tone % 64);
    out[2] = uint8_t(std::clamp(keyShift, 0, 48));
}

// Rhythm setup timbre: M1-M64 (0-63) are the unit's tones i11-i88 (or the cache slot holding the MT-32's timbre),
// R1-R64 (64-127) its rhythm tones.
uint8_t Mt32Translator::translateRhythmTimbre(uint8_t value, int key) const {
    if (value < 64) {
        if (key >= 0 && rhythmSlot_[size_t(key)] >= 0 && cacheActive()) return uint8_t(cacheFirst_ + rhythmSlot_[size_t(key)]);
        return value;
    }
    const int timbre = value - 64, standIn = rhythmStandIn(timbre);
    if (presetBanks() && (rhythmIsExact(timbre) || standIn != kRhythmOff)) return value;
    return uint8_t(64 + standIn);
}

void Mt32Translator::translateTone(const Tone& tone, uint32_t base, uint32_t offset, Output& out) const {
    const uint8_t value = tone.data[offset];
    if (offset < kToneCommonSize) {
        out.set(base + offset, value);
        if (tone.known() && (offset == kStructure12 || offset == kStructure34)) {
            // The structure decides which partials play PCM waves, and so which need their waves translated.
            const int first = offset == kStructure12 ? 0 : 2;
            translatePartial(tone, base, first, out);
            translatePartial(tone, base, first + 1, out);
        }
        return;
    }
    const uint32_t partial = (offset - kToneCommonSize) / kPartialSize, parameter = (offset - kToneCommonSize) % kPartialSize;
    const bool dependent = parameter == kPitchCoarse || parameter == kPitchFine || parameter == kWaveform || parameter == kPcmWave;
    if (!dependent) {
        out.set(base + offset, value);
    } else if (tone.known()) {
        translatePartial(tone, base, int(partial), out);
    } else if (parameter == kPcmWave) {
        // Byte by byte: a bank-1 wave, as the waveform byte (which holds the bank) may not come with it.
        const uint8_t waveform = tone.data[offset - (kPcmWave - kWaveform)];
        out.set(base + offset, waveMapping(value + ((waveform & 2) != 0 ? 128 : 0), tone.drumKit).bank1Wave);
    } else if (parameter == kWaveform) {
        out.set(base + offset, value & 1);
    } else {
        out.set(base + offset, value);
    }
}

void Mt32Translator::translatePartial(const Tone& tone, uint32_t base, int partial, Output& out) const {
    const uint32_t start = kToneCommonSize + uint32_t(partial) * kPartialSize;
    const uint8_t* parameters = &tone.data[start];
    const uint8_t structure = tone.data[partial < 2 ? kStructure12 : kStructure34];
    const bool pcm = structure < 13 && (kPartialStruct[structure] & (partial % 2 == 0 ? 2 : 1)) != 0;
    base += start;
    if (!pcm) {
        out.set(base + kPitchCoarse, parameters[kPitchCoarse]);
        out.set(base + kPitchFine, parameters[kPitchFine]);
        out.set(base + kWaveform, parameters[kWaveform]);
        out.set(base + kPcmWave, parameters[kPcmWave]);
        return;
    }
    uint8_t wave = 0, coarse = 0, fine = 0;
    translatePcm(parameters[kPcmWave] + ((parameters[kWaveform] & 2) != 0 ? 128 : 0), parameters[kPitchCoarse], parameters[kPitchFine],
                 wave, coarse, fine, roomyToms_, tone.drumKit);
    out.set(base + kPitchCoarse, coarse);
    out.set(base + kPitchFine, fine);
    out.set(base + kWaveform, uint8_t((parameters[kWaveform] & 1) | (wave >= 128 ? 2 : 0)));
    out.set(base + kPcmWave, uint8_t(wave & 127));
}

void Mt32Translator::selectTimbre(int part) {
    const std::array<uint8_t, 16>& temp = patchTemp_[size_t(part)];
    Tone& tone = toneTemp_[size_t(part)];
    const int group = temp[kGroup] & 3, number = temp[kNumber] & 63;
    toneSent_[size_t(part)] = true;  // The target loads the translated tone itself...
    toneToSend_[size_t(part)] = false;
    partSlot_[size_t(part)] = -1;
    slotFill_[size_t(part)] = false;
    const Mt32Presets::Timbre* preset = nullptr;
    if (presets_ && group < 2) {
        preset = &presets_->melodic[size_t(group * 64 + number)];
    } else if (presets_ && group == 3 && size_t(number) < presets_->rhythm.size()) {
        preset = &presets_->rhythm[size_t(number)];
    }
    if (group == 2) {
        tone = toneMemory_[size_t(number)];  // Memory timbre: known if the MT-32 side wrote it
        if (!memoryInUnit_ && tone.known()) {
            toneSent_[size_t(part)] = false;  // The unit's i tone is its own: send the MT-32's
            toneToSend_[size_t(part)] = true;
        }
    } else if (preset != nullptr) {
        std::memcpy(tone.data.data(), preset->data(), kToneSize);
        tone.written.set();
        // ...unless it plays a stand-in, which the MT-32's own timbre replaces at once where it is chosen (the preset
        // banks hold the MT-32's own already).
        const bool exact = group < 2 ? presetIsExact(group * 64 + number) : rhythmIsExact(number);
        toneSent_[size_t(part)] = exact && presetBanks();
        toneToSend_[size_t(part)] = exact && !presetBanks();
    } else {
        tone.written.reset();  // A preset whose MT-32 data is not known here
    }
    tone.drumKit = group == 3;  // A rhythm timbre keeps the drum kit's waves (see waveMapping())
}

void Mt32Translator::sendTones(uint8_t deviceId, std::vector<uint8_t>& out) {
    for (size_t part = 0; part < 8; part++) {
        if (!toneToSend_[part]) continue;
        toneToSend_[part] = false;
        Output output;
        for (uint32_t offset = 0; offset < kToneSize; offset++) translateTone(toneTemp_[part], kToneTemp + uint32_t(part) * kToneSize, offset, output);
        emit(output, deviceId, out);
        if (slotFill_[part] && partSlot_[part] >= 0) appendToneWrite(int(part), partSlot_[part], deviceId, out);
        slotFill_[part] = false;
        toneSent_[part] = true;
    }
}

void Mt32Translator::programChange(int channel, int program, uint8_t deviceId, std::vector<uint8_t>& sysexOut) {
    for (size_t part = 0; part < 8; part++) {
        if (system_[kSystemChannels + part] != channel) continue;
        std::memcpy(patchTemp_[part].data(), patchMemory_[size_t(program & 127)].data(), 8);
        selectTimbre(int(part));
        resolveSlot(int(part));
        if (!memoryInUnit_) {
            // The part's timbre temp as the patch sets it (tone, key shift, fine tune, bender range, assign mode, reverb).
            Output output;
            writeByte(kPatchTemp + uint32_t(part) * 16 + kGroup, patchTemp_[part][kGroup], output);
            for (uint32_t offset = kKeyShift + 1; offset <= kReverbSwitch; offset++) {
                writeByte(kPatchTemp + uint32_t(part) * 16 + offset, patchTemp_[part][offset], output);
            }
            emit(output, deviceId, sysexOut);
        }
    }
    sendTones(deviceId, sysexOut);
}

void Mt32Translator::emit(const Output& output, uint8_t deviceId, std::vector<uint8_t>& out) {
    std::vector<uint8_t> run;
    size_t i = 0;
    while (i < output.bytes.size()) {
        if (output.bytes[i] < 0) {
            i++;
            continue;
        }
        const size_t first = i;
        run.clear();
        while (i < output.bytes.size() && output.bytes[i] >= 0 && run.size() < 256) run.push_back(uint8_t(output.bytes[i++]));
        appendDataSet(out, deviceId, output.start + uint32_t(first), run.data(), run.size());
    }
}
