// MT-32 panpot (0 = right) for a position right of centre.
uint8_t mt32Pan(int right) {
    return uint8_t(std::clamp(7 - right, 0, 14));
}

uint8_t checksum(const uint8_t* data, size_t length) {
    unsigned sum = 0;
    for (size_t i = 0; i < length; i++) sum += data[i];
    return uint8_t((128 - sum % 128) % 128);
}

void appendDataSet(std::vector<uint8_t>& out, uint8_t deviceId, uint32_t address, const uint8_t* data, size_t length) {
    const size_t start = out.size();
    const uint8_t header[] = {0xF0, 0x41, deviceId, 0x16, 0x12, uint8_t((address >> 14) & 0x7F), uint8_t((address >> 7) & 0x7F),
                              uint8_t(address & 0x7F)};
    out.insert(out.end(), header, header + sizeof(header));
    out.insert(out.end(), data, data + length);
    out.push_back(checksum(&out[start + 5], 3 + length));
    out.push_back(0xF7);
}

bool inMt32Area(uint32_t address) {
    return (address >= kPatchTemp && address < kRhythmSetupEnd) || (address >= kToneTemp && address < kToneTempEnd) ||
           (address >= kPatchMemory && address < kPatchMemoryEnd) || (address >= kToneMemory && address < kToneMemoryEnd) ||
           (address >= kSystem && address < kSystem + kSystemSize) || (address >= kDisplay && address < kDisplay + 0x4000) ||
           address >= kReset;
}

