void Mt32Translator::Output::set(uint32_t address, uint8_t value) {
    if (bytes.empty()) {
        start = address;
    } else if (address < start) {
        bytes.insert(bytes.begin(), size_t(start - address), int16_t(-1));
        start = address;
    }
    const size_t index = size_t(address - start);
    if (index >= bytes.size()) bytes.resize(index + 1, int16_t(-1));
    bytes[index] = value;
}

