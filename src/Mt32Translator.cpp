void Mt32Translator::unitChannelsFor(uint8_t channel, std::vector<uint8_t>& out) const {
    out.clear();
    if (target_ != Target::D20) {
        out.push_back(channel);  // The unit's parts follow the MT-32 channels (system area)
        return;
    }
    for (size_t part = 0; part < 9; part++) {
        if (system_[kSystemChannels + part] != channel) continue;
        const uint8_t unit = unitChannels_[part];
        if (unit < 16 && std::find(out.begin(), out.end(), unit) == out.end()) out.push_back(unit);
    }
}

uint8_t Mt32Translator::scaledVolume(uint8_t channel) const {
    const unsigned master = masterVolumeAsVolume_ ? std::min<unsigned>(system_[kSystemMasterVolume], 100) : 100;
    return uint8_t((volume_[channel & 15] * master + 50) / 100);
}

void Mt32Translator::appendVolumes(std::vector<uint32_t>& out) const {
    std::vector<uint8_t> units;
    bool done[16] = {};
    for (size_t part = 0; part < 9; part++) {
        const uint8_t channel = system_[kSystemChannels + part];
        if (channel >= 16 || done[channel]) continue;
        done[channel] = true;
        unitChannelsFor(channel, units);
        for (uint8_t unit : units) out.push_back(uint32_t(0xB0 | unit) | (7u << 8) | (uint32_t(scaledVolume(channel)) << 16));
    }
}

const Mt32Translator::WaveMapping& Mt32Translator::waveMapping(int mt32Wave, bool drumKit) {
    if (drumKit) {
        for (const DrumKitWave& drum : kDrumKitWaves) {
            if (drum.mt32Wave == (mt32Wave & 0xFF)) return drum.mapping;
        }
    }
    return kWaves[mt32Wave & 0xFF];
}

void Mt32Translator::translatePcm(int mt32Wave, uint8_t coarse, uint8_t fine, uint8_t& wave, uint8_t& outCoarse, uint8_t& outFine,
                                  bool roomyToms, bool drumKit) {
    // Adds a correction in cents, carrying whole semitones from the fine pitch (0-100, 50 = none) into the coarse.
    auto correct = [&](int8_t addCoarse, int8_t addFine) {
        const int cents = (int(coarse) + addCoarse) * 100 + int(std::min<uint8_t>(fine, 100)) - 50 + addFine;
        const int semitones = cents + 50 >= 0 ? (cents + 50) / 100 : -((49 - cents) / 100);  // Rounded to nearest
        outCoarse = uint8_t(std::clamp(semitones, 0, 96));
        outFine = uint8_t(std::clamp(cents - int(outCoarse) * 100 + 50, 0, 100));
        return semitones >= 0 && semitones <= 96;
    };
    if (roomyToms) {
        for (const WaveFallback& tom : kRoomyToms) {
            if (tom.mt32Wave != (mt32Wave & 0xFF)) continue;
            wave = tom.wave;
            correct(tom.coarse, tom.fine);
            return;
        }
    }
    const WaveMapping& mapping = waveMapping(mt32Wave, drumKit);
    wave = mapping.wave;
    if (correct(mapping.coarse, mapping.fine)) return;
    for (const WaveFallback& fallback : kWaveFallbacks) {
        if (fallback.mt32Wave != (mt32Wave & 0xFF)) continue;
        const uint8_t clampedCoarse = outCoarse, clampedFine = outFine;
        if (correct(fallback.coarse, fallback.fine)) {
            wave = fallback.wave;
        } else {
            outCoarse = clampedCoarse;  // Out of range either way: keep the primary wave, clamped
            outFine = clampedFine;
        }
        return;
    }
}

