bool Mt32Translator::presetIsExact(int mt32Timbre) const {
    if (!presets_) return false;
    if (mode_ == PresetMode::Exact) return true;
    return mode_ == PresetMode::Hybrid && presetChoices_[size_t(mt32Timbre & 0x7F)].exact;
}

bool Mt32Translator::rhythmIsExact(int mt32RhythmTimbre) const {
    const int timbre = mt32RhythmTimbre & 0x3F;
    if (!presets_ || size_t(timbre) >= presets_->rhythm.size()) return false;
    if (mode_ == PresetMode::Exact) return true;
    return mode_ == PresetMode::Hybrid && rhythmChoices_[size_t(timbre)].exact;
}

int Mt32Translator::rhythmStandIn(int mt32RhythmTimbre) const {
    const RhythmChoice& choice = rhythmChoices_[size_t(mt32RhythmTimbre & 0x3F)];
    return choice.tone >= 0 ? choice.tone : rhythmToneFor(mt32RhythmTimbre);
}

namespace {

std::vector<std::string> splitChoices(const std::string& text) {
    std::vector<std::string> entries;
    size_t start = 0;
    while (start <= text.size()) {
        const size_t end = std::min(text.find(';', start), text.size());
        if (end > start) entries.push_back(text.substr(start, end - start));
        start = end + 1;
    }
    return entries;
}

}  // namespace

std::string Mt32Translator::presetChoicesText(const PresetChoices& choices) {
    std::string text;
    for (int timbre = 0; timbre < 128; timbre++) {
        const PresetChoice& choice = choices[size_t(timbre)];
        if (choice == defaultPresetChoice(timbre)) continue;
        if (!text.empty()) text += ';';
        text += std::to_string(timbre) + ':' + std::to_string(choice.tone) + ':' + std::to_string(choice.keyShift) + ':' + (choice.exact ? '1' : '0');
    }
    return text;
}

void Mt32Translator::parsePresetChoices(const std::string& text, PresetChoices& choices) {
    for (int timbre = 0; timbre < 128; timbre++) choices[size_t(timbre)] = defaultPresetChoice(timbre);
    for (const std::string& entry : splitChoices(text)) {
        int timbre = 0, tone = 0, shift = 0, exact = 0;
        if (std::sscanf(entry.c_str(), "%d:%d:%d:%d", &timbre, &tone, &shift, &exact) != 4 || timbre < 0 || timbre > 127) continue;
        if (tone < 0 || tone > 255 || (tone >= 128 && tone < 192)) continue;
        PresetChoice choice;
        choice.tone = uint8_t(tone);
        choice.keyShift = int8_t(std::clamp(shift, -24, 24));
        choice.exact = exact != 0;
        choices[size_t(timbre)] = choice;
    }
}

std::string Mt32Translator::rhythmChoicesText(const RhythmChoices& choices) {
    std::string text;
    for (int timbre = 0; timbre < 64; timbre++) {
        const RhythmChoice& choice = choices[size_t(timbre)];
        if (choice == RhythmChoice()) continue;
        if (!text.empty()) text += ';';
        text += std::to_string(timbre) + ':' + std::to_string(choice.tone) + ':' + (choice.exact ? '1' : '0');
    }
    return text;
}

void Mt32Translator::parseRhythmChoices(const std::string& text, RhythmChoices& choices) {
    choices.fill(RhythmChoice());
    for (const std::string& entry : splitChoices(text)) {
        int timbre = 0, tone = 0, exact = 0;
        if (std::sscanf(entry.c_str(), "%d:%d:%d", &timbre, &tone, &exact) != 3 || timbre < 0 || timbre > 63) continue;
        if (tone < -1 || tone > int(kRhythmOff)) continue;
        RhythmChoice choice;
        choice.tone = int8_t(tone);
        choice.exact = exact != 0;
        choices[size_t(timbre)] = choice;
    }
}

