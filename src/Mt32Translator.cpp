// Tone cache

void Mt32Translator::setToneCache(int first, int last) {
    cache_.clear();
    cacheFailed_ = false;
    first = std::max(first, 0);
    last = std::min(last, 63);
    if (first <= last) {
        cacheFirst_ = first;
        cache_.resize(size_t(last - first + 1));
    }
    partSlot_.fill(-1);
    slotFill_.fill(false);
    rhythmSlot_.fill(-1);
}

void Mt32Translator::clearToneCache() {
    // Slots that parts or rhythm keys play from stay reserved until they select something else.
    for (CacheSlot& slot : cache_) slot.valid = false;
    cacheFailed_ = false;
}

std::vector<std::vector<uint8_t>> Mt32Translator::toneCacheContents() const {
    std::vector<std::vector<uint8_t>> contents(cache_.size());
    for (size_t i = 0; i < cache_.size(); i++) {
        if (cache_[i].valid) contents[i].assign(cache_[i].tone.begin(), cache_[i].tone.end());
    }
    return contents;
}

void Mt32Translator::restoreToneCache(const std::vector<std::vector<uint8_t>>& contents) {
    for (size_t i = 0; i < cache_.size() && i < contents.size(); i++) {
        if (contents[i].size() != kToneSize) continue;
        std::memcpy(cache_[i].tone.data(), contents[i].data(), kToneSize);
        cache_[i].valid = true;
        cache_[i].lastUse = 0;
    }
}

Mt32Translator::CacheStats Mt32Translator::toneCacheStats() const {
    CacheStats stats;
    stats.slots = int(cache_.size());
    for (const CacheSlot& slot : cache_) stats.used += slot.valid ? 1 : 0;
    stats.hits = cacheHits_;
    stats.misses = cacheMisses_;
    stats.failed = cacheFailed_;
    return stats;
}

int Mt32Translator::cacheFind(const uint8_t* tone) const {
    for (size_t i = 0; i < cache_.size(); i++) {
        if (cache_[i].valid && std::memcmp(cache_[i].tone.data(), tone, kToneSize) == 0) return int(i);
    }
    return -1;
}

int Mt32Translator::cacheAllocate() {
    std::vector<bool> inUse(cache_.size(), false);
    for (int slot : partSlot_) {
        if (slot >= 0) inUse[size_t(slot)] = true;
    }
    for (int slot : rhythmSlot_) {
        if (slot >= 0) inUse[size_t(slot)] = true;
    }
    int oldest = -1;
    for (size_t i = 0; i < cache_.size(); i++) {
        if (inUse[i]) continue;
        if (!cache_[i].valid) return int(i);
        if (oldest < 0 || cache_[i].lastUse < cache_[size_t(oldest)].lastUse) oldest = int(i);
    }
    return oldest;
}

void Mt32Translator::appendToneWrite(int part, int slot, uint8_t deviceId, std::vector<uint8_t>& out) const {
    const uint8_t request[2] = {uint8_t(cacheFirst_ + slot), 0};  // Internal memory
    appendDataSet(out, deviceId, kWriteRequest + uint32_t(part) * 2, request, sizeof(request));
}

void Mt32Translator::resolveSlot(int part) {
    partSlot_[size_t(part)] = -1;
    slotFill_[size_t(part)] = false;
    if (!toneToSend_[size_t(part)] || !cacheActive()) return;
    uint8_t tone[kToneSize];
    unitTone(toneTemp_[size_t(part)], tone);
    int slot = cacheFind(tone);
    if (slot >= 0) {
        cacheHits_++;
        toneToSend_[size_t(part)] = false;  // The timbre temp points at the slot: the unit loads it
        toneSent_[size_t(part)] = true;
    } else {
        slot = cacheAllocate();
        if (slot < 0) return;  // Every slot in use: the tone goes to the part alone
        std::memcpy(cache_[size_t(slot)].tone.data(), tone, kToneSize);
        cache_[size_t(slot)].valid = true;
        slotFill_[size_t(part)] = true;
        cacheMisses_++;
    }
    cache_[size_t(slot)].lastUse = ++cacheClock_;
    partSlot_[size_t(part)] = slot;
}

int Mt32Translator::resolveRhythmKey(int key, uint8_t deviceId, std::vector<uint8_t>& out, bool& borrowed) {
    rhythmSlot_[size_t(key)] = -1;
    const uint8_t value = rhythmSetup_[size_t(key)][0];
    if (!cacheActive() || value >= 64 || !toneMemory_[value].known()) return -1;
    uint8_t tone[kToneSize];
    unitTone(toneMemory_[value], tone);
    int slot = cacheFind(tone);
    if (slot >= 0) {
        cacheHits_++;
    } else {
        slot = cacheAllocate();
        if (slot < 0) return -1;
        std::memcpy(cache_[size_t(slot)].tone.data(), tone, kToneSize);
        cache_[size_t(slot)].valid = true;
        cacheMisses_++;
        // The rhythm part has no tone temp: the tone goes through part 8's, which is restored afterwards.
        Output output;
        for (uint32_t offset = 0; offset < kToneSize; offset++) translateTone(toneMemory_[value], kToneTemp + 7 * kToneSize, offset, output);
        emit(output, deviceId, out);
        appendToneWrite(7, slot, deviceId, out);
        borrowed = true;
    }
    cache_[size_t(slot)].lastUse = ++cacheClock_;
    rhythmSlot_[size_t(key)] = slot;
    return slot;
}

void Mt32Translator::restorePart(int part, uint8_t deviceId, std::vector<uint8_t>& out) {
    // The tone write left the part on the slot it filled: select its own tone again.
    Output output;
    writeByte(kPatchTemp + uint32_t(part) * 16 + kGroup, patchTemp_[size_t(part)][kGroup], output);
    emit(output, deviceId, out);
    if (partSlot_[size_t(part)] < 0 && toneSent_[size_t(part)] && toneTemp_[size_t(part)].known()) {
        Output tone;
        for (uint32_t offset = 0; offset < kToneSize; offset++) {
            translateTone(toneTemp_[size_t(part)], kToneTemp + uint32_t(part) * kToneSize, offset, tone);
        }
        emit(tone, deviceId, out);
    }
}

void Mt32Translator::preloadToneCache(uint8_t deviceId, std::vector<uint8_t>& out) {
    if (!cacheActive()) return;
    bool borrowed = false;
    size_t stored = 0;
    for (size_t number = 0; number < toneMemory_.size() && stored < cache_.size(); number++) {
        if (!toneMemory_[number].known()) continue;
        uint8_t tone[kToneSize];
        unitTone(toneMemory_[number], tone);
        const int found = cacheFind(tone);
        if (found >= 0) {
            cache_[size_t(found)].lastUse = ++cacheClock_;
            stored++;
            continue;
        }
        const int slot = cacheAllocate();
        if (slot < 0) break;
        std::memcpy(cache_[size_t(slot)].tone.data(), tone, kToneSize);
        cache_[size_t(slot)].valid = true;
        cache_[size_t(slot)].lastUse = ++cacheClock_;
        Output output;
        for (uint32_t offset = 0; offset < kToneSize; offset++) translateTone(toneMemory_[number], kToneTemp + 7 * kToneSize, offset, output);
        emit(output, deviceId, out);
        appendToneWrite(7, slot, deviceId, out);
        borrowed = true;
        stored++;
    }
    if (borrowed) restorePart(7, deviceId, out);
}

bool Mt32Translator::writeRequestResult(uint8_t result, uint8_t deviceId, std::vector<uint8_t>& out) {
    if (result == 0 || cache_.empty() || cacheFailed_) return result == 0;
    cacheFailed_ = true;  // The slots do not hold what the translator wrote: stop using them
    for (CacheSlot& slot : cache_) slot.valid = false;
    for (int part = 0; part < 8; part++) {
        if (partSlot_[size_t(part)] < 0) continue;
        partSlot_[size_t(part)] = -1;
        slotFill_[size_t(part)] = false;
        Output output;
        writeByte(kPatchTemp + uint32_t(part) * 16 + kGroup, patchTemp_[size_t(part)][kGroup], output);
        if (toneTemp_[size_t(part)].known()) {
            for (uint32_t offset = 0; offset < kToneSize; offset++) {
                translateTone(toneTemp_[size_t(part)], kToneTemp + uint32_t(part) * kToneSize, offset, output);
            }
        }
        emit(output, deviceId, out);
    }
    Output rhythm;
    for (int key = 0; key < 85; key++) {
        if (rhythmSlot_[size_t(key)] < 0) continue;
        rhythmSlot_[size_t(key)] = -1;
        writeByte(kRhythmSetup + uint32_t(key) * 4, rhythmSetup_[size_t(key)][0], rhythm);
    }
    emit(rhythm, deviceId, out);
    return false;
}

