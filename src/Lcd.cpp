const ImU32 kBezel = IM_COL32(20, 20, 22, 255);

// The lines between a real LCD's dots are hair thin, about a twelfth of the dot pitch (0.05 of 0.6 mm on HD44780-type
// modules). The gap between dots here is one whole pixel, a quarter of the pitch at the usual size, so a gap pixel
// shows the glass only as much as such a line would cover of it, over the dots on either side: an anti-aliased
// hairline, with every dot still on whole pixels.
constexpr float kLineWidth = 0.08f;  // Of the dot pitch

ImVec4 mix(const ImVec4& dots, const ImVec4& glass, float cover) {
    return ImVec4(dots.x + (glass.x - dots.x) * cover, dots.y + (glass.y - dots.y) * cover, dots.z + (glass.z - dots.z) * cover, 1.0f);
}

ImVec4 average(const ImVec4& a, const ImVec4& b) {
    return ImVec4((a.x + b.x) * 0.5f, (a.y + b.y) * 0.5f, (a.z + b.z) * 0.5f, 1.0f);
}

