bool draw(const char* id, const std::string& text, int dotPitch, const Colors& colors) {
    // Whole pixels throughout: a dot and the one-pixel gap after it make the pitch; a character is 5 x 8 dots, and the
    // space between characters and between the lines is one dot wide, as on the units' LCDs (a whole blank dot
    // position, with the gaps on both sides, looks like two dots).
    const int pitch = std::max(dotPitch, 3);
    const int gap = 1;
    const int dot = pitch - gap;
    // How much of a gap pixel the line between two dots covers (kLineWidth), and of one where two lines cross.
    const float line = std::min(1.0f, kLineWidth * float(pitch) / float(gap));
    const float crossing = 1.0f - (1.0f - line) * (1.0f - line);
    const int charPitch = 5 * pitch - gap + dot;
    const int linePitch = 8 * pitch - gap + dot;
    const int margin = pitch + gap;
    const int bezel = std::max(2, pitch / 2 + 1);
    const int textWidth = (kColumns - 1) * charPitch + 5 * pitch - gap;
    const int textHeight = (kRows - 1) * linePitch + 8 * pitch - gap;
    const ImVec2 size(float(2 * (margin + bezel) + textWidth), float(2 * (margin + bezel) + textHeight));

    const ImVec2 cursor = ImGui::GetCursorScreenPos();
    const ImVec2 origin(std::floor(cursor.x), std::floor(cursor.y));
    const bool clicked = ImGui::InvisibleButton(id, size);
    ImDrawList* drawList = ImGui::GetWindowDrawList();
    drawList->AddRectFilled(origin, ImVec2(origin.x + size.x, origin.y + size.y), kBezel, float(bezel));
    const ImVec2 glassMin(origin.x + float(bezel), origin.y + float(bezel));
    const ImVec2 glassMax(origin.x + size.x - float(bezel), origin.y + size.y - float(bezel));
    drawList->AddRectFilled(glassMin, glassMax, colors.background, float(pitch) * 0.5f);

    const ImVec4 glass = ImGui::ColorConvertU32ToFloat4(colors.background);
    const ImVec4 lit = ImGui::ColorConvertU32ToFloat4(colors.dotOn);
    const ImVec4 unlit = ImGui::ColorConvertU32ToFloat4(colors.dotOff);
    auto fill = [&](float x, float y, int width, int height, const ImVec4& color) {
        drawList->AddRectFilled(ImVec2(x, y), ImVec2(x + float(width), y + float(height)), ImGui::ColorConvertFloat4ToU32(color));
    };
    for (int row = 0; row < kRows; row++) {
        for (int column = 0; column < kColumns; column++) {
            const size_t index = size_t(row * kColumns + column);
            const uint8_t raw = index < text.size() ? uint8_t(text[index]) : uint8_t(' ');
            const bool inverted = (raw & 0x80) != 0;
            const uint8_t code = raw & 0x7F;
            const uint8_t* glyph = kFont[code >= 0x20 ? code - 0x20 : 0];
            const float cellX = glassMin.x + float(margin + column * charPitch);
            const float cellY = glassMin.y + float(margin + row * linePitch);
            ImVec4 dots[8][5];
            for (int y = 0; y < 8; y++) {
                const uint8_t bits = y < 7 ? glyph[y] : 0;
                for (int x = 0; x < 5; x++) {
                    const bool on = ((bits >> (4 - x)) & 1) != inverted;
                    dots[y][x] = on ? lit : unlit;
                    fill(cellX + float(x * pitch), cellY + float(y * pitch), dot, dot, dots[y][x]);
                }
            }
            // The gaps: after each dot, to its right, below it, and where those meet.
            for (int y = 0; y < 8; y++) {
                for (int x = 0; x < 5; x++) {
                    const float left = cellX + float(x * pitch);
                    const float top = cellY + float(y * pitch);
                    if (x < 4) fill(left + float(dot), top, gap, dot, mix(average(dots[y][x], dots[y][x + 1]), glass, line));
                    if (y < 7) fill(left, top + float(dot), dot, gap, mix(average(dots[y][x], dots[y + 1][x]), glass, line));
                    if (x < 4 && y < 7) {
                        const ImVec4 around = average(average(dots[y][x], dots[y][x + 1]), average(dots[y + 1][x], dots[y + 1][x + 1]));
                        fill(left + float(dot), top + float(dot), gap, gap, mix(around, glass, crossing));
                    }
                }
            }
        }
    }
    return clicked;
}

